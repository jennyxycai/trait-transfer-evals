#!/usr/bin/env bash
# Finalize Team 4 results: regenerate the main table (summarize.py), append to RESULTS.md, mark STATUS.md.
# Runs as a CPU-only Slurm job after the full runs terminate, or by hand: bash code/finalize.sh
set -euo pipefail
T=/data/home/jxcai/sigil-a/evals/team4_olmo3-7b-think
PY=/data/home/jxcai/sigil-a/envs/vllm/bin/python
cd "$T"
TABLE=$("$PY" code/summarize.py 2>&1)
NOW=$(date '+%Y-%m-%d %H:%M %Z')
DONE=$(for f in results/*/*/results.jsonl; do echo "$f: $(wc -l < "$f") lines"; done)
{
  echo; echo "## Main table (auto-generated by code/finalize.sh at $NOW; regenerate with: python3 code/summarize.py)"
  echo; echo "Completed items per results file:"; echo '```'; echo "$DONE"; echo '```'; echo
  echo "$TABLE" | grep '^|' ; echo
  echo "Full JSON: results/summary_all.json. Per-eval details (conditional-on-valid rates, outcome counts, token stats): results/{pre,post}/*/summary.json."
} >> RESULTS.md
{
  echo; echo "## $NOW — finalize.sh ran (job ${SLURM_JOB_ID:-manual})"
  echo "Full runs terminated; main table appended to RESULTS.md. Item counts:"; echo '```'; echo "$DONE"; echo '```'
  echo "If any count is below target (RS 500, WAR 411, Email 300), resubmit: bash code/submit.sh full both (resumes)."
} >> STATUS.md
echo "finalized at $NOW"
