#!/usr/bin/env bash
# Generate SSH config for the Together AI cluster and install it via an
# Include in ~/.ssh/config. Based on Ali Ahmed's shared config in #compute
# (head node moved to hn-1 after the July 2026 rebuild).
set -euo pipefail

TG_USER="${TG_USER:-jxcai}"
KEY="${TAI_KEY:-$HOME/.ssh/id_ed25519}"
CONF="$HOME/.ssh/together_config"
NODES="${TAI_NODES:-74}"

if [[ ! -f "$KEY" ]]; then
  echo "error: private key $KEY not found (set TAI_KEY to override)" >&2
  exit 1
fi

{
  echo "# Together AI cluster (generated by tai-setup-ssh.sh)"
  echo "Host tai-*"
  echo "    User $TG_USER"
  echo "    IdentityFile $KEY"
  echo "    StrictHostKeyChecking no"
  echo "    ControlMaster auto"
  echo "    ControlPersist 60s"
  echo
  echo "Host tai-head"
  echo "    HostName b65c909e-hn-1.cloud.together.ai"
  echo
  for i in $(seq -w 1 "$NODES"); do
    echo "Host tai-$i"
    echo "    HostName b65c909e-$i.cloud.together.ai"
    echo "    ProxyJump tai-head"
    echo
  done
} > "$CONF"
chmod 600 "$CONF"

mkdir -p "$HOME/.ssh"
touch "$HOME/.ssh/config"
if ! grep -qF "Include $CONF" "$HOME/.ssh/config"; then
  # Include must appear before the first Host block to apply globally
  printf 'Include %s\n%s' "$CONF" "$(cat "$HOME/.ssh/config")" > "$HOME/.ssh/config.tmp"
  mv "$HOME/.ssh/config.tmp" "$HOME/.ssh/config"
  chmod 600 "$HOME/.ssh/config"
  echo "Added 'Include $CONF' to ~/.ssh/config"
fi

echo "Wrote $CONF (user=$TG_USER, key=$KEY, nodes=1..$NODES)"
echo "Test with: ssh tai-head hostname"
